// Command rivergen writes River's schema as a FAIR migration (F-001 T-08).
//
// River's tables are applied by `iam migrate` like any other migration, so no
// service ever runs DDL at runtime. The output places River in the `river`
// schema owned by fair_owner, records the versions in river.river_migration
// (so River's own validation sees a migrated schema), and grants app_rw only
// what the scope worker needs.
//
// A River migration that adds an enum value must commit before a later one
// uses it, so the output is split at such boundaries into separate files
// (each file is one transaction).
//
// Usage (once per River upgrade; committed migrations are never edited):
//
//	go run ./db/rivergen -from 1 -to 4 -out db/migrations/0007_river_v1_v4.sql
//	go run ./db/rivergen -from 5 -to 6 -out db/migrations/0008_river_v5_v6.sql
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/jackc/pgx/v5"
	"github.com/riverqueue/river/riverdriver/riverpgxv5"
	"github.com/riverqueue/river/rivermigrate"
)

const schema = "river"

func main() {
	from := flag.Int("from", 1, "first River migration version to include")
	to := flag.Int("to", 0, "last River migration version to include (0 = latest)")
	out := flag.String("out", "", "output file")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "rivergen: -out is required")
		os.Exit(2)
	}

	m, err := rivermigrate.New[pgx.Tx](riverpgxv5.New(nil), nil)
	if err != nil {
		fmt.Fprintln(os.Stderr, "rivergen:", err)
		os.Exit(1)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- F-001 T-08: River job tables (generated by db/rivergen; do not edit).\n")
	last := m.AllVersions()[len(m.AllVersions())-1].Version
	if *to == 0 || *to > last {
		*to = last
	}
	fmt.Fprintf(&b, "-- River migration line \"main\", versions %d..%d, in schema %s.\n\n", *from, *to, schema)
	if *from == 1 {
		fmt.Fprintf(&b, "CREATE SCHEMA %s AUTHORIZATION fair_owner;\nREVOKE ALL ON SCHEMA %s FROM PUBLIC;\n\n", schema, schema)
	}
	var versions []string
	for _, v := range m.AllVersions() {
		if v.Version < *from || v.Version > *to {
			continue
		}
		fmt.Fprintf(&b, "-- River %03d %s\n%s\n\n", v.Version, v.Name, strings.ReplaceAll(v.SQLUp, "/* TEMPLATE: schema */", schema+"."))
		versions = append(versions, fmt.Sprintf("%d", v.Version))
	}
	// River 005 added river_migration.line (copying older rows as 'main').
	if *to < 5 {
		fmt.Fprintf(&b, "INSERT INTO %s.river_migration (version) VALUES (%s)\nON CONFLICT DO NOTHING;\n\n", schema, strings.Join(versions, "), ("))
	} else {
		fmt.Fprintf(&b, "INSERT INTO %s.river_migration (line, version) VALUES ('main', %s)\nON CONFLICT DO NOTHING;\n\n", schema, strings.Join(versions, "), ('main', "))
	}
	fmt.Fprintf(&b, `-- The scope worker (app_rw) runs River: job tables and functions only.
GRANT USAGE ON SCHEMA %[1]s TO app_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA %[1]s TO app_rw;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA %[1]s TO app_rw;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA %[1]s TO app_rw;
`, schema)
	if err := os.WriteFile(*out, []byte(b.String()), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "rivergen:", err)
		os.Exit(1)
	}
}
