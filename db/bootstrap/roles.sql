-- FAIR Risk Platform: database role bootstrap (F-001 T-02, AC-27).
--
-- Run ONCE per instance by the installer (F-014) or a DBA, connected to the
-- platform database as a role with CREATEROLE (superuser on self-managed
-- Postgres; rds_superuser / azure_pg_admin on managed services). Requires
-- PostgreSQL 16+ (GRANT ... WITH INHERIT FALSE, SET TRUE).
--
--   psql "$ADMIN_URL" -v ON_ERROR_STOP=1 \
--     -v migrator_password="$(openssl rand -base64 32)" \
--     -v app_rw_password="$(openssl rand -base64 32)" \
--     -v app_engine_password="$(openssl rand -base64 32)" \
--     -f db/bootstrap/roles.sql
--
-- Passwords are generated by the installer and stored only in the secrets
-- store; nothing ships with a default credential (ADR-006). The script is
-- idempotent: re-running it re-asserts every attribute and grant.
--
-- Role model:
--   fair_owner     NOLOGIN  owns platform schemas and tables
--   authz_definer  NOLOGIN  owns the authz schema, the DB-context HMAC key
--                           table and (T-09) the SECURITY DEFINER functions
--   app_migrator   LOGIN    runs migrations by SET ROLE to the owners; owns nothing
--   app_rw         LOGIN    API services; NOBYPASSRLS; owns nothing
--   app_engine     LOGIN    Python simulation engine; NOBYPASSRLS; narrower grants

\set ON_ERROR_STOP on
SET password_encryption = 'scram-sha-256';

DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['fair_owner','authz_definer','app_migrator','app_rw','app_engine'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('CREATE ROLE %I', r);
    END IF;
  END LOOP;
END $$;

-- Owners can never log in. NOBYPASSRLS everywhere; table owners are covered
-- separately by FORCE ROW LEVEL SECURITY on every BU-owned table (T-09).
ALTER ROLE fair_owner    NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
ALTER ROLE authz_definer NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
ALTER ROLE app_migrator  LOGIN   NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
ALTER ROLE app_rw        LOGIN   NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
ALTER ROLE app_engine    LOGIN   NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;

ALTER ROLE app_migrator PASSWORD :'migrator_password';
ALTER ROLE app_rw       PASSWORD :'app_rw_password';
ALTER ROLE app_engine   PASSWORD :'app_engine_password';

-- The migrator may switch to the owner roles explicitly but inherits none of
-- their privileges, so an accidental unqualified CREATE fails instead of
-- creating an object owned by a login role.
GRANT fair_owner    TO app_migrator WITH INHERIT FALSE, SET TRUE;
GRANT authz_definer TO app_migrator WITH INHERIT FALSE, SET TRUE;

-- Safe session defaults for application roles.
ALTER ROLE app_rw     SET row_security = on;
ALTER ROLE app_engine SET row_security = on;
ALTER ROLE app_rw     SET statement_timeout = '30s';
ALTER ROLE app_rw     SET idle_in_transaction_session_timeout = '60s';

-- Database-level privileges: nobody but the platform roles may connect;
-- only the owner roles may create schemas; no temp tables for apps.
DO $$
BEGIN
  EXECUTE format('REVOKE ALL ON DATABASE %I FROM PUBLIC', current_database());
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO app_migrator, app_rw, app_engine', current_database());
  EXECUTE format('GRANT CREATE ON DATABASE %I TO fair_owner, authz_definer', current_database());
END $$;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
