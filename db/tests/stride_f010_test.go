// E, S: the delegated context cannot be used to write, for another user,
// outside a run, or with an outdated scope.
func TestSTRIDEF010DelegatedContext(t *testing.T) {
	e := docFixture(t) // erin reads A and A1's documents
	e.mustOwner(fmt.Sprintf("SELECT authz.add_ctx_key('%s', decode('%s', 'hex'), 'report')", reportKey.ID, hex.EncodeToString(reportKey.Secret)))
	root := e.adminQuery("SELECT id FROM iam.bu WHERE parent_id IS NULL")
	run := e.adminQuery(fmt.Sprintf(`INSERT INTO report.run (requested_by, bu_id, kind, formats) SELECT id, '%s', 'register', '{csv}' FROM iam.app_user
		WHERE email = 'erin@example.test' RETURNING id`, root))
	tok := e.mint("erin", reportKey)
	nonce := strings.Split(tok, ".")[5]
	e.adminQuery("UPDATE report.run SET state = 'running', context_nonce = '" + nonce + "' WHERE id = '" + run + "' RETURNING id")
	readOnly := func(token, sql string) (string, error) {
		return e.as("app_rw", fmt.Sprintf("BEGIN READ ONLY; SET LOCAL authz.ctx = '%s'; %s; COMMIT;", token, sql))
	}
	if out, err := readOnly(tok, visibleDocs); err != nil || strings.TrimSpace(out) != "a,a1" {
		t.Fatalf("the running run's token: %q %v", out, err)
	}
	// No write gets through, not even through a definer function: the
	// transaction is read-only, and read-write ones see no user.
	if out, err := readOnly(tok, "SELECT report.add_run('register', '"+root+"', '{}', '{csv}', 'x', 1)"); err == nil {
		t.Errorf("a definer write under the report token: %s", out)
	}
	if out, err := e.asCtx(tok, visibleDocs); err != nil || strings.TrimSpace(out) != "-" {
		t.Errorf("the report token in a read-write transaction: %q %v", out, err)
	}
	// The app role cannot mark another user's run running to borrow it.
	if got := e.adminState("SET ROLE app_rw; UPDATE report.run SET context_nonce = '" + strings.Repeat("0", 32) + "'"); got != "42501" {
		t.Errorf("app_rw sets a nonce: %s", got)
	}
	// A scope change makes the token stale: nothing is read with it.
	e.mustOwner(grant("platform", "user:erin", "Executive Viewer", "B"))
	e.drain()
	if out, err := readOnly(tok, visibleDocs); err != nil || strings.TrimSpace(out) != "-" {
		t.Errorf("a token of the old scope version: %q %v", out, err)
	}
	// A token signed with a session key is a session token: it carries no
	// report purpose, and a report-purpose key is not a session key.
	if got := e.adminQuery("SELECT purpose FROM authz.ctx_key WHERE key_id = '" + reportKey.ID + "'"); got != "report" {
		t.Errorf("the report key's purpose: %q", got)
	}
}

