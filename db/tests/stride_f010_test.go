// T: report content cannot inject into PDF, CSV or JSON.
func TestSTRIDEF010Injection(t *testing.T) {
	f := strideF010Fixture(t)
	ra := f.ra
	const evil = `=HYPERLINK("http://evil.example/x","open") <script>alert(1)</script> ) Tj /JavaScript (x) /URI (http://evil.example)`
	owner := ra.adminQuery("SELECT id FROM iam.app_user WHERE email = 'owen@example.test'")
	if got := f.rg.call(t, "POST", "owen", "/api/v1/register/risks", map[string]any{"bu_id": ra.bu["A1"], "change_note": "x",
		"document": map[string]any{"schema_version": 1, "title": evil, "owner": owner, "state": "open", "scenarios": []any{}}}); got.code != 201 {
		t.Fatalf("create: %d %s", got.code, got.raw)
	}
	run := f.generate(t, "owen", ra.bu["A"], map[string]any{"formats": []string{"pdf", "csv", "json"}})
	if run["state"] != "succeeded" {
		t.Fatalf("report: %v", run)
	}
	// CSV: the title is a text cell, its formula made inert.
	z, err := zip.NewReader(bytes.NewReader(f.file(t, "owen", run, "csv")), int64(len(f.file(t, "owen", run, "csv"))))
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, zf := range z.File {
		if !strings.HasSuffix(zf.Name, ".csv") {
			continue
		}
		rc, _ := zf.Open()
		b, _ := io.ReadAll(rc)
		_ = rc.Close()
		cr := csv.NewReader(bytes.NewReader(bytes.TrimPrefix(b, []byte("\uFEFF"))))
		cr.FieldsPerRecord = -1 // the marking line, then the table
		rows, err := cr.ReadAll()
		if err != nil {
			t.Fatalf("%s: %v", zf.Name, err)
		}
		for _, r := range rows {
			for _, c := range r {
				if c != "" && strings.ContainsRune("=+-@\t\r", rune(c[0])) {
					t.Errorf("%s: a live formula cell %q", zf.Name, c)
				}
				if c == "'"+evil {
					found = true
				}
			}
		}
	}
	if !found {
		t.Error("the title is not in the CSV as inert text")
	}
	// JSON: the title as a string value, the document canonical.
	var doc map[string]any
	j := f.file(t, "owen", run, "json")
	if err := json.Unmarshal(j, &doc); err != nil || !strings.Contains(string(j), `HYPERLINK(\"http://evil.example/x\"`) {
		t.Errorf("json: %v", err)
	}
	// PDF: the title is text, and the file has no actions, links,
	// JavaScript or external resources.
	pdf := f.file(t, "owen", run, "pdf")
	text, err := report.Text(pdf, true)
	if err != nil || !strings.Contains(text, "/JavaScript (x)") {
		t.Errorf("pdf text: %v %q", err, text[:min(len(text), 300)])
	}
	for _, bad := range []string{"/JS ", "/JavaScript <<", "/S /JavaScript", "/S /URI", "/Launch", "/OpenAction", "/AA ", "/URI (", "/EmbeddedFile", "http://evil"} {
		if bytes.Contains(stripStreams(pdf), []byte(bad)) {
			t.Errorf("the PDF's objects contain %q", bad)
		}
	}
}

// stripStreams is a PDF's object syntax with its (compressed) streams cut
// out, so that only dictionaries and arrays are searched.
func stripStreams(pdf []byte) []byte {
	var out []byte
	for {
		i := bytes.Index(pdf, []byte("stream\n"))
		if i < 0 {
			return append(out, pdf...)
		}
		out = append(out, pdf[:i]...)
		j := bytes.Index(pdf[i:], []byte("endstream"))
		if j < 0 {
			return out
		}
		pdf = pdf[i+j+len("endstream"):]
	}
}

// T: every file's SHA-256 is the same in the listing, the download's
// header, the recorded event and the bytes.
func TestSTRIDEF010Digests(t *testing.T) {
	f := strideF010Fixture(t)
	ra := f.ra
	run := f.generate(t, "owen", ra.bu["A"], map[string]any{"formats": []string{"pdf", "csv", "json"}})
	id := run["id"].(string)
	var event struct {
		Attributes map[string]string `json:"attributes"`
	}
	if err := json.Unmarshal([]byte(ra.adminQuery("SELECT body FROM audit.intake WHERE body ->> 'type' = 'report.generated' AND body ->> 'target' = 'report_run:"+id+"'")), &event); err != nil {
		t.Fatal(err)
	}
	for _, fl := range run["files"].([]any) {
		m := fl.(map[string]any)
		format, listed := m["format"].(string), m["sha256"].(string)
		code, body, hdr := f.re.download(t, "owen", id, format)
		sum := sha256.Sum256(body)
		if code != 200 || hex.EncodeToString(sum[:]) != listed || hdr != "sha256="+listed || !strings.Contains(event.Attributes["files"], listed) {
			t.Errorf("%s: listed %s, header %s, bytes %x, event %s", format, listed, hdr, sum, event.Attributes["files"])
		}
	}
	// A copy altered in the store no longer matches the recorded digest.
	f.re.store.mu.Lock()
	f.re.store.corrupt = true
	f.re.store.mu.Unlock()
	if code, body, hdr := f.re.download(t, "owen", id, "json"); code == 200 {
		sum := sha256.Sum256(body)
		if "sha256="+hex.EncodeToString(sum[:]) == hdr {
			t.Error("an altered file matches its recorded digest")
		}
	}
}

