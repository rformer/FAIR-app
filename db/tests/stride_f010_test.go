// generate requests a report as user and works its job; the run as read.
func (f *f010Env) generate(t *testing.T, user, bu string, body map[string]any) map[string]any {
	t.Helper()
	b := map[string]any{"reason": "STRIDE suite"}
	for k, v := range body {
		b[k] = v
	}
	got := f.re.request(t, user, bu, b)
	if got.code != 202 {
		t.Fatalf("request as %s: %d %s", user, got.code, got.raw)
	}
	id := got.body["id"].(string)
	if err := f.re.attempt(t, id, 1); err != nil {
		t.Logf("attempt %s: %v", id, err)
	}
	return f.re.call(t, "GET", user, "/api/v1/reports/"+id, nil).body
}

