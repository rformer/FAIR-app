// Package ghreplay replays recorded GitHub REST API responses for the
// change-evidence tests (F-012 T-17): a fixture file lists requests and the
// responses GitHub gave (hand-written in the shape of GitHub's API), and
// Replay answers them without a network. A request the fixture does not
// list is answered 404 and remembered (Misses), so a test notices calls it
// did not expect.
package ghreplay

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"sort"
	"strings"
	"sync"
)

// Fixture is one recorded response.
type Fixture struct {
	// URI is the request's path and query ("/repos/o/r/pulls?state=closed");
	// the query's order does not matter.
	URI    string `json:"uri"`
	Status int    `json:"status,omitempty"` // default 200
	// Next is the URI of the next page, sent as a Link rel="next" header.
	Next string          `json:"next,omitempty"`
	Body json.RawMessage `json:"body,omitempty"`
	// Text is a raw (non-JSON) body, such as a release asset.
	Text string `json:"text,omitempty"`
}

// File is a fixture file.
type File struct {
	Requests []Fixture `json:"requests"`
}

// Replay answers requests from fixtures.
type Replay struct {
	mu     sync.Mutex
	byURI  map[string]Fixture
	misses []string
	seen   map[string]int
}

// Load reads a fixture file.
func Load(file string) (*Replay, error) {
	b, err := os.ReadFile(file) // #nosec G304 -- test fixture
	if err != nil {
		return nil, err
	}
	var f File
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&f); err != nil {
		return nil, fmt.Errorf("ghreplay: %s: %w", file, err)
	}
	r := &Replay{byURI: map[string]Fixture{}, seen: map[string]int{}}
	for _, x := range f.Requests {
		k, err := key(x.URI)
		if err != nil {
			return nil, err
		}
		if _, dup := r.byURI[k]; dup {
			return nil, fmt.Errorf("ghreplay: %s: %s listed twice", file, x.URI)
		}
		r.byURI[k] = x
	}
	return r, nil
}

// Set adds or replaces a response (for bodies a test computes, such as
// signatures made with a key generated by the test).
func (r *Replay) Set(uri string, status int, body []byte) {
	k, err := key(uri)
	if err != nil {
		panic(err)
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.byURI[k] = Fixture{URI: uri, Status: status, Text: string(body)}
}

// Misses are the requests no fixture answered.
func (r *Replay) Misses() []string {
	r.mu.Lock()
	defer r.mu.Unlock()
	return append([]string(nil), r.misses...)
}

// Count is how often uri was requested.
func (r *Replay) Count(uri string) int {
	k, _ := key(uri)
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.seen[k]
}

// Do answers req.
func (r *Replay) Do(req *http.Request) (*http.Response, error) {
	if req.Method != http.MethodGet {
		return nil, fmt.Errorf("ghreplay: %s %s: only GET is recorded", req.Method, req.URL)
	}
	k, err := key(req.URL.RequestURI())
	if err != nil {
		return nil, err
	}
	r.mu.Lock()
	x, ok := r.byURI[k]
	r.seen[k]++
	if !ok {
		r.misses = append(r.misses, k)
	}
	r.mu.Unlock()
	h := http.Header{}
	if !ok {
		return respond(req, http.StatusNotFound, h, []byte(`{"message":"Not Found"}`)), nil
	}
	status := x.Status
	if status == 0 {
		status = http.StatusOK
	}
	if x.Next != "" {
		h.Set("Link", fmt.Sprintf(`<%s://%s%s>; rel="next"`, req.URL.Scheme, req.URL.Host, x.Next))
	}
	body := []byte(x.Text)
	if len(x.Body) > 0 {
		body = x.Body
		h.Set("Content-Type", "application/json")
	}
	return respond(req, status, h, body), nil
}

func respond(req *http.Request, status int, h http.Header, body []byte) *http.Response {
	return &http.Response{
		Status:        fmt.Sprintf("%d %s", status, http.StatusText(status)),
		StatusCode:    status,
		Proto:         "HTTP/1.1",
		ProtoMajor:    1,
		ProtoMinor:    1,
		Header:        h,
		Body:          io.NopCloser(bytes.NewReader(body)),
		ContentLength: int64(len(body)),
		Request:       req,
	}
}

// key normalizes a URI: the path, then the query sorted by name and value.
func key(uri string) (string, error) {
	u, err := url.Parse(uri)
	if err != nil {
		return "", fmt.Errorf("ghreplay: %q: %w", uri, err)
	}
	q := u.Query()
	names := make([]string, 0, len(q))
	for n := range q {
		names = append(names, n)
	}
	sort.Strings(names)
	var parts []string
	for _, n := range names {
		vs := append([]string(nil), q[n]...)
		sort.Strings(vs)
		for _, v := range vs {
			parts = append(parts, url.QueryEscape(n)+"="+url.QueryEscape(v))
		}
	}
	if len(parts) == 0 {
		return u.EscapedPath(), nil
	}
	return u.EscapedPath() + "?" + strings.Join(parts, "&"), nil
}
