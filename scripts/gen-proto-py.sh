#!/usr/bin/env bash
# Regenerates the engine's Python gRPC code from api/proto/fair/engine (F-005
# T-03). Generated code is committed; run this after changing engine.proto,
# from the repository root:
#   docker run --rm -v "$PWD:/src" -w /src python:3.12-slim-bookworm scripts/gen-proto-py.sh
# The Go side is scripts/gen-proto.sh. The proto is mapped to
# fairsim/_proto/ so the generated imports resolve inside the package.
set -euo pipefail
GRPCIO_TOOLS=1.84.2
pip install --quiet --disable-pip-version-check --no-cache-dir "grpcio-tools==${GRPCIO_TOOLS}"
out=engine/fairsim/_proto
rm -rf "$out"
mkdir -p "$out"
python -m grpc_tools.protoc -I"fairsim/_proto=api/proto" \
  --python_out=engine --pyi_out=engine --grpc_python_out=engine \
  fairsim/_proto/fair/engine/v1/engine.proto
for d in "$out" "$out/fair" "$out/fair/engine" "$out/fair/engine/v1"; do
  printf '# Generated by scripts/gen-proto-py.sh; do not edit.\n' > "$d/__init__.py"
done
